'use strict';
const router=require('express').Router();
const {requireRole}=require('../middlewares/auth');
const {asyncRoute}=require('../middlewares/errors');
const c=require('../controllers/adminController');
router.use(requireRole('ADMINISTRADOR'));
router.get('/',asyncRoute(c.dashboard));
const doc=require('../controllers/documentController');
const reports=require('../controllers/reporteController');
router.get('/documentos',asyncRoute(doc.listAdmin));
router.post('/documentos',asyncRoute(doc.upload));
router.post('/documentos/:id/eliminar',asyncRoute(doc.remove));
router.get('/reportes',asyncRoute(reports.admin));
router.get('/reportes/:formato',asyncRoute(reports.exportAdmin));
router.get('/:type',asyncRoute(c.list));
router.get('/:type/nuevo',asyncRoute(c.form));
router.get('/:type/:id/editar',asyncRoute(c.form));
router.get('/:type/:id/detalle',asyncRoute(c.detail));
router.post('/:type',asyncRoute(c.save));
router.post('/:type/:id',asyncRoute(c.save));
router.post('/:type/:id/:kind',asyncRoute(c.status));
module.exports=router;
